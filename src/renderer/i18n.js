let current = 'en';

export const setLanguage = code => {
  current = DICTIONARIES[code] ? code : 'en';
  document.documentElement.lang = current;
  return current;
};

export const detectLanguage = stored => {
  if (DICTIONARIES[stored]) return stored;
  const preferred = (navigator.language || 'en').slice(0, 2);
  return DICTIONARIES[preferred] ? preferred : 'en';
};

export const t = (key, vars) => {
  const template = DICTIONARIES[current][key] ?? DICTIONARIES.en[key] ?? key;
  return vars ? template.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '') : template;
};

export const translateDom = (root = document) => {
  root.querySelectorAll('[data-t]').forEach(node => {
    node.textContent = t(node.dataset.t);
  });
  root.querySelectorAll('[data-t-placeholder]').forEach(node => {
    node.placeholder = t(node.dataset.tPlaceholder);
  });
  root.querySelectorAll('[data-t-title]').forEach(node => {
    node.title = t(node.dataset.tTitle);
    node.setAttribute('aria-label', t(node.dataset.tTitle));
  });
};
